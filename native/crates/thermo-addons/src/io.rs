//! 附加功能的 I/O 抽象
//!
//! 附加功能**自己不直接碰文件系统** —— I/O 由宿主注入：
//!
//! | 好处 | 说明 |
//! |---|---|
//! | 可离线测试 | 用假的 I/O 实现即可跑全部逻辑（见 `tests/`） |
//! | 唯一出口 | "谁写节点"这件事有单一出口，便于审计与事件记录 |
//! | 不依赖平台 | 本 crate 因此不含任何路径常量，路径由功能自己声明、宿主执行 |

/// 宿主借给附加功能的 I/O 能力
///
/// 实现方在 `thermo-cli`（真机用 `std::fs`，测试用内存假节点树）。
pub trait AddonIo {
    /// 路径是否存在
    fn exists(&mut self, path: &str) -> bool;

    /// 是否可写
    ///
    /// sysfs 上不能只看权限位（属主可能是 `system:system`，实际以 root 运行时可写），
    /// 实现方应当用"试开写句柄"的方式判断。
    fn writable(&mut self, path: &str) -> bool;

    /// 读取（去掉首尾空白）
    fn read(&mut self, path: &str) -> Result<String, String>;

    /// 写入（**一次写完整值**，不追加换行由实现方决定）
    fn write(&mut self, path: &str, value: &str) -> Result<(), String>;

    /// 当前是否插着充电器（充电中或已充满）
    ///
    /// # 用途：省电
    ///
    /// 附加功能据此**在未充电时跳过巡检**：
    ///
    /// | 项 | 说明 |
    /// |---|---|
    /// | 必要性 | 限制值只可能在充电时被改写；没插电时限制值是多少都无所谓 |
    /// | 代价 | 每次巡检都是一次 sysfs 读取，会打断 CPU 深度睡眠 |
    ///
    /// 宿主（`worker`）也用同样的判据把"未充电 + 无客户端"整段
    /// 进入深度阻塞，真正做到空闲零唤醒。
    ///
    /// # 默认实现
    ///
    /// 返回 `true`（始终视为"在充电"）—— 既有的测试替身不必改动，
    /// 行为退回"每次都巡检"（安全但费电）。真机宿主会给出准确值。
    fn is_plugged(&mut self) -> bool {
        true
    }

    /// **后台启动一个短命子进程**（不等它结束）
    ///
    /// # 为什么需要它
    ///
    /// PPS 的"金标动画"要靠连发 5 条 `am broadcast`，单条约 50~150 ms，
    /// 合计 **0.5~1 秒**。而 worker 主循环在充电中是 **3 秒一拍** ——
    /// 同步执行会把温控采样推迟近一秒，属于"附加功能拖累核心功能"，
    /// 违反本 crate 的隔离契约。
    ///
    /// ⇒ 交给子进程跑，worker 立刻返回。子进程 `Stdio::null()`，
    ///   输出不进主进程管道；worker 每拍顺手 `try_wait` 回收僵尸。
    ///
    /// # 参数
    ///
    /// `args` 是**子命令部分**（如 `["pps", "burst", "--power", "100"]`），
    /// 宿主用 `std::env::current_exe()` 定位同一个 `thermo` 二进制。
    ///
    /// # 默认实现
    ///
    /// 返回 `Err`（不支持）。调用方必须把失败当作**非致命**：
    /// 记一条日志即可，节点写入照常进行 —— 广播只是锦上添花。
    fn spawn_detached(&mut self, _args: &[&str]) -> Result<(), String> {
        Err("本宿主不支持启动子进程".to_string())
    }
}
