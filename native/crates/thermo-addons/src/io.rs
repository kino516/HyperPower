//! 附加功能的 I/O 抽象
//!
//! 附加功能**自己不直接碰文件系统** —— I/O 由宿主注入：
//!
//! | 好处 | 说明 |
//! |---|---|
//! | 可离线测试 | 用假的 I/O 实现即可跑全部逻辑（见 `tests/`） |
//! | 唯一出口 | "谁写节点"这件事有单一出口，便于审计与事件记录 |
//! | 不依赖平台 | 本 crate 因此不含任何路径常量，路径由功能自己声明、宿主执行 |

/// 宿主借给附加功能的 I/O 能力
///
/// 实现方在 `thermo-cli`（真机用 `std::fs`，测试用内存假节点树）。
pub trait AddonIo {
    /// 路径是否存在
    fn exists(&mut self, path: &str) -> bool;

    /// 是否可写
    ///
    /// sysfs 上不能只看权限位（属主可能是 `system:system`，实际以 root 运行时可写），
    /// 实现方应当用"试开写句柄"的方式判断。
    fn writable(&mut self, path: &str) -> bool;

    /// 读取（去掉首尾空白）
    fn read(&mut self, path: &str) -> Result<String, String>;

    /// 写入（**一次写完整值**，不追加换行由实现方决定）
    fn write(&mut self, path: &str, value: &str) -> Result<(), String>;

    /// 当前是否插着充电器（充电中或已充满）
    ///
    /// # 用途：省电
    ///
    /// 附加功能据此**在未充电时跳过巡检**：
    ///
    /// | 项 | 说明 |
    /// |---|---|
    /// | 必要性 | 限制值只可能在充电时被改写；没插电时限制值是多少都无所谓 |
    /// | 代价 | 每次巡检都是一次 sysfs 读取，会打断 CPU 深度睡眠 |
    ///
    /// 宿主（`worker`）也用同样的判据把"未充电 + 无客户端"整段
    /// 进入深度阻塞，真正做到空闲零唤醒。
    ///
    /// # 默认实现
    ///
    /// 返回 `true`（始终视为"在充电"）—— 既有的测试替身不必改动，
    /// 行为退回"每次都巡检"（安全但费电）。真机宿主会给出准确值。
    fn is_plugged(&mut self) -> bool {
        true
    }
}
